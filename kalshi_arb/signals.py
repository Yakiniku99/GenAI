"""Live "What moved" signals: biggest 24h repricings, each scored for how much
it looks like informed trading versus noise, plus a feed of large trades.

Evidence behind the design (see research/informed_flow.md, regenerated by
`python -m kalshi_arb research`):

* Trades of 1,000+ contracts earn about +2c within an hour from the taker's
  side; small trades lose about the half-spread. Size is the clearest trace
  of informed ("shark") flow in Kalshi's anonymous tape, but the edge is
  mostly gone within hours, so the big-trade feed is a heads-up, not a
  follow-later strategy.
* The average 3c+ move partly reverses. Moves with tight spreads, heavy
  volume vs normal, many trades and a high share of big trades revert least.
  The score weights those features by how strongly they separated
  continuation from reversal, and is checked out of sample.
"""

from __future__ import annotations

import bisect
import json
from concurrent.futures import ThreadPoolExecutor, as_completed
from datetime import datetime, timezone
from pathlib import Path

from .client import KalshiClient
from .flow import MidSeries, big_trade_threshold, move_features, parse_trades
from .macro import market_mid

MODEL_PATH = Path(__file__).parent / "informed_model.json"
SHARK_SIZE = 1000          # contracts: the size bucket with clearly positive markouts
MIN_MOVE = 0.03            # dollars of YES mid over 24h
MIN_VOLUME_24H = 50        # contracts
FEATURE_LABELS = {
    "spread": "Bid-ask spread",
    "volume_ratio": "Volume vs normal",
    "n_trades": "Number of trades",
    "big_share": "Share from big trades",
    "flow_imbalance": "Buyers vs sellers in the move's direction",
}


def load_model() -> dict:
    try:
        return json.loads(MODEL_PATH.read_text())
    except (OSError, ValueError):
        return {"features": {}}


def informed_score(features: dict, model: dict) -> dict:
    """0-100: percentile of each feature against past moves, weighted by how
    strongly that feature predicted moves holding (sign flips "low is good")."""
    total = points = 0.0
    parts = []
    for name, spec in (model.get("features") or model).items():
        if not isinstance(spec, dict) or "quantiles" not in spec:
            continue
        v = features.get(name)
        if v is None:
            continue
        qs, w = spec["quantiles"], spec["weight"]
        pct = bisect.bisect_left(qs, v) / len(qs)
        good = pct if w > 0 else 1 - pct
        total += abs(w)
        points += abs(w) * good
        parts.append({"feature": name, "label": FEATURE_LABELS.get(name, name), "value": v,
                      "percentile": round(pct, 2), "good": round(good, 2), "weight": round(abs(w), 2)})
    score = round(100 * points / total) if total else 50
    label = "informed" if score >= 60 else "noise" if score < 40 else "mixed"
    return {"score": score, "label": label, "components": parts}


def _mid_change(m: dict) -> tuple[float | None, float | None]:
    now, prev = market_mid(m, False, 0.15), market_mid(m, True, 0.15)
    return now, prev


def find_movers(events: list[dict], limit: int = 20) -> list[dict]:
    """Largest 24h mid moves, one per event, with how many sibling strikes agree."""
    best: dict[str, dict] = {}
    for e in events:
        rows = []
        for m in e.get("markets") or []:
            if m.get("status") != "active":
                continue
            now, prev = _mid_change(m)
            vol = float(m.get("volume_24h_fp") or 0)
            if now is None or prev is None:
                continue
            rows.append((m, now, prev, vol))
        for m, now, prev, vol in rows:
            d = now - prev
            if abs(d) < MIN_MOVE or vol < MIN_VOLUME_24H or not (0.02 < now < 0.98 or 0.02 < prev < 0.98):
                continue
            cur = best.get(e["event_ticker"])
            if cur and abs(cur["change"]) >= abs(d):
                continue
            direction = 1 if d > 0 else -1
            ladder = not e.get("mutually_exclusive") and m.get("strike_type") in ("greater", "greater_or_equal", "less", "less_or_equal")
            sibs = [(n - p) for mm, n, p, _ in rows if mm is not m]
            agree = sum(1 for x in sibs if x * direction >= 0.01) if ladder else None
            best[e["event_ticker"]] = {
                "ticker": m["ticker"], "series_ticker": e.get("series_ticker", ""), "event_ticker": e["event_ticker"],
                "event_title": e.get("title", ""), "label": m.get("yes_sub_title") or m["ticker"],
                "mid": round(now, 4), "prev_mid": round(prev, 4), "change": round(d, 4), "direction": direction,
                "volume_24h": vol, "open_interest": float(m.get("open_interest_fp") or 0),
                "siblings": len(sibs) if ladder else None, "siblings_agree": agree,
                "close_time": m.get("close_time"),
            }
    return sorted(best.values(), key=lambda r: -abs(r["change"]))[:limit]


def _sparkline(mids: MidSeries, start: float, end: float, points: int = 56) -> list[list[float]]:
    if not len(mids):
        return []
    step = (end - start) / points
    out = []
    for i in range(points + 1):
        t = start + i * step
        v = mids.at(t)
        if v is not None:
            out.append([round(t), round(v, 4)])
    return out


def build_signals(client: KalshiClient, events: list[dict], workers: int = 8,
                  n_movers: int = 20, n_active: int = 40, now: datetime | None = None) -> tuple[dict, list[str]]:
    now = now or datetime.now(timezone.utc)
    end = int(now.timestamp())
    model = load_model()
    movers = find_movers(events, n_movers)

    # Most active markets (for the big-trade feed) besides the movers.
    active = []
    for e in events:
        for m in e.get("markets") or []:
            mid = market_mid(m)
            if m.get("status") == "active" and mid is not None and 0.03 < mid < 0.97:
                active.append((float(m.get("volume_24h_fp") or 0), m, e))
    active.sort(key=lambda x: -x[0])
    meta = {r["ticker"]: {"series": r["series_ticker"], "event_title": r["event_title"], "label": r["label"],
                          "event_ticker": r["event_ticker"]} for r in movers}
    for vol, m, e in active[:n_active]:
        meta.setdefault(m["ticker"], {"series": e["series_ticker"], "event_title": e.get("title", ""),
                                      "label": m.get("yes_sub_title") or m["ticker"], "event_ticker": e["event_ticker"]})
    mid_now = {m["ticker"]: market_mid(m) for e in events for m in e.get("markets") or []}
    mover_set = {r["ticker"] for r in movers}

    def load(tk: str):
        is_mover = tk in mover_set
        days = 7 if is_mover else 1
        trades = parse_trades(client.trades(tk, min_ts=end - days * 86400, max_ts=end, max_pages=5 if is_mover else 2))
        candles = client.candlesticks(meta[tk]["series"], tk, end - 8 * 86400, end, 60) if is_mover else []
        return tk, trades, MidSeries(candles)

    errors: list[str] = []
    loaded: dict[str, tuple] = {}
    with ThreadPoolExecutor(max_workers=workers) as pool:
        futures = [pool.submit(load, tk) for tk in meta]
        for fut in as_completed(futures):
            try:
                tk, trades, mids = fut.result()
                loaded[tk] = (trades, mids)
            except Exception as e:
                errors.append(f"signals: {e}")

    for r in movers:
        if r["ticker"] not in loaded:
            continue
        trades, mids = loaded[r["ticker"]]
        big = big_trade_threshold(trades)
        f = move_features(trades, mids, end - 86400, end, r["direction"], big) if len(mids) else {}
        r["features"] = f
        r["big_threshold"] = big
        r["informed"] = informed_score(f, model)
        r["sparkline"] = _sparkline(mids, end - 7 * 86400, end)
        r["move_start"] = end - 86400
        w = [t for t in trades if t.ts > end - 86400]
        r["big_trades"] = [{"ts": round(t.ts), "price": t.price, "size": t.size, "side": "yes" if t.sign > 0 else "no",
                            "with_move": t.sign == r["direction"]}
                           for t in sorted((t for t in w if t.size >= big), key=lambda t: -t.size)[:5]]

    feed = []
    for tk, (trades, _) in loaded.items():
        cur = mid_now.get(tk)
        for t in trades:
            if t.ts <= end - 86400 or t.size < SHARK_SIZE:
                continue
            since = None if cur is None else round((cur - t.price) * (1 if t.sign > 0 else -1) * 100, 1)
            feed.append({"ticker": tk, **meta[tk], "ts": round(t.ts), "side": "yes" if t.sign > 0 else "no",
                         "price": t.price, "size": t.size, "notional": round(t.notional, 2),
                         "mid_now": cur, "cents_since": since})
    feed.sort(key=lambda x: -x["ts"])
    return {
        "movers": movers,
        "big_trades": feed[:60],
        "shark_size": SHARK_SIZE,
        "markets_checked": len(loaded),
        "model": {k: model.get(k) for k in ("generated_at", "trades", "moves", "validation", "markouts_cents")},
    }, errors
